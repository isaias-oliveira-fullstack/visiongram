/** Enum para cores básicas */
export enum BasicColor {
    /** Cor padrão */
    DEFAULT = 'sky',

    /** Cor de sucesso */
    SUCCESS = 'green',

    /** Cor informativa */
    INFO = 'indigo',

    /** Cor de aviso */
    WARNING = 'yellow',

    /** Cor de perigo */
    DANGER = 'red',

    /** Contorno com cor padrão */
    OUTLINE  = 'outline', 
    
    /** Cor clara */
    LIGHT = 'light',

    /** Cor escura */
    DARK = 'dark'
}